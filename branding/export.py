#!/usr/bin/env python3
"""Deterministic Moader logo exports; Python 3, Pillow 12.2.0, librsvg 2.62.2.

Run: python3 branding/export.py
The only authored geometry is mark.svg. Every other mark derives from its path.
"""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, ImageFont, PngImagePlugin, __version__ as pillow_version

ROOT = Path(__file__).resolve().parent
NS = "{http://www.w3.org/2000/svg}"
BLUE = "#175f79"
LIGHT = "#eef2f3"
DARK = "#18252d"
TINT = "#7bbad3"
SIZE = 96
RECIPE = (
    "Moader project logo. Original geometric vector authored in branding/mark.svg. "
    "No external artwork, font outlines, image generation model or claimed designer. "
    "Recipe: python3 branding/export.py; rasterize the exact canonical SVG path using "
    "librsvg, with Workbench Blue #175f79 and white foreground for hbmenu; render at "
    "1024x1024 then Lanczos downsample to 256x256; opaque RGB JPEG quality=95, "
    "subsampling=0, optimize=False, progressive=False. Native mask: white canonical "
    "SVG at 384x384, Lanczos downsample to 96x96, retain alpha only. Contact sheet "
    "uses actual exports at 16,32,64,256 pixels on the existing light/dark tokens. "
    "Geometry and outputs are content-hashed in manifest.json."
)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render(svg: str, size: int) -> Image.Image:
    png = subprocess.run(
        ["rsvg-convert", "--width", str(size), "--height", str(size)],
        input=svg.encode(), stdout=subprocess.PIPE, check=True,
    ).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def png_save(im: Image.Image, path: Path, origin: str) -> None:
    metadata = PngImagePlugin.PngInfo()
    metadata.add_text("impeccable:prompt", origin)
    metadata.add_text("Description", origin)
    im.save(path, pnginfo=metadata, optimize=False)


def main() -> None:
    source = (ROOT / "mark.svg").read_bytes()
    tree = ET.fromstring(source)
    assert tree.attrib == {"viewBox": "0 0 64 64", "fill": "currentColor"}
    paths = tree.findall(NS + "path")
    assert len(paths) == 1 and len(tree) == 2, "Only title and one canonical path allowed"
    path = paths[0].attrib["d"]
    assert paths[0].attrib == {"d": path}

    def svg(color: str, background: str = "", rounded: bool = False) -> str:
        tile = (f'<rect width="64" height="64" rx="{12 if rounded else 0}" '
                f'fill="{background}"/>') if background else ""
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
                f'<title>Moader</title>{tile}<path fill="{color}" d="{path}"/></svg>\n')

    favicon = svg("#fff", BLUE, True)
    hbmenu = svg("#fff", BLUE)
    (ROOT / "favicon.svg").write_text(favicon)
    (ROOT / "hbmenu-source.svg").write_text(hbmenu)
    icon = render(hbmenu, 1024).resize((256, 256), Image.Resampling.LANCZOS).convert("RGB")
    provenance = RECIPE + " Canonical source SHA-256: " + digest(source) + "."
    icon.save(ROOT / "hbmenu.jpg", quality=95, subsampling=0, optimize=False,
              progressive=False, comment=("impeccable:prompt\0" + provenance).encode("utf-8"))
    assert Image.open(ROOT / "hbmenu.jpg").info["comment"].decode() == "impeccable:prompt\0" + provenance

    alpha = render(svg("#fff"), SIZE * 4).resize((SIZE, SIZE), Image.Resampling.LANCZOS).getchannel("A")
    png_save(alpha, ROOT / "mark-alpha.png", provenance)
    mask = alpha.tobytes()
    rows = ["    " + ",".join(str(n) for n in mask[i:i + 24]) + "," for i in range(0, len(mask), 24)]
    header = (
        "// Generated by branding/export.py from mark.svg. Do not hand-edit.\n"
        f"// Source SHA-256: {digest(source)}\n"
        f"// Alpha SHA-256: {digest(mask)}; row-major, y-down, 0=clear, 255=opaque.\n"
        "#pragma once\n#include <cstdint>\n\nnamespace moader { namespace branding {\n"
        f"static constexpr int kMarkWidth = {SIZE};\nstatic constexpr int kMarkHeight = {SIZE};\n"
        f"static constexpr std::uint8_t kMarkAlpha[{SIZE * SIZE}] = {{\n"
        + "\n".join(rows)
        + "\n};\nstatic_assert(sizeof(kMarkAlpha) == kMarkWidth * kMarkHeight, \"Moader alpha dimensions\");\n"
        "}} // namespace moader::branding\n"
    )
    (ROOT / "mark-alpha.hpp").write_text(header)

    # Evidence uses delivered SVG/JPEG/mask, not a separately redrawn logo.
    previews = ROOT / "previews"
    previews.mkdir(exist_ok=True)
    sheet = Image.new("RGB", (1104, 1560), "#fff")
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default(size=16)
    small = ImageFont.load_default(size=13)
    draw.text((24, 16), "Moader / canonical export inspection", fill=BLUE, font=font)
    xs = [24, 72, 144, 264]
    sizes = [16, 32, 64, 256]
    for row, kind in enumerate(["mark", "favicon", "hbmenu", "native-mask"]):
        y = 52 + row * 330
        for col, (bg, fg, theme) in enumerate([(LIGHT, BLUE, "light"), (DARK, TINT, "dark")]):
            x0 = col * 552
            draw.rectangle((x0, y, x0 + 551, y + 329), fill=bg)
            draw.text((x0 + 24, y + 12), f"{kind} / {theme}", fill=fg, font=font)
            for x, size in zip(xs, sizes):
                if kind == "mark":
                    actual = render(svg(fg), size)
                elif kind == "favicon":
                    actual = render((ROOT / "favicon.svg").read_text(), size)
                elif kind == "hbmenu":
                    actual = Image.open(ROOT / "hbmenu.jpg").convert("RGBA").resize((size, size), Image.Resampling.LANCZOS)
                else:
                    actual = Image.new("RGBA", (SIZE, SIZE), fg)
                    actual.putalpha(alpha)
                    actual = actual.resize((size, size), Image.Resampling.LANCZOS)
                plate = Image.new("RGBA", (size, size), bg)
                plate.alpha_composite(actual)
                png_save(plate.convert("RGB"), previews / f"{kind}-{size}-{theme}.png", provenance)
                sheet.paste(plate.convert("RGB"), (x0 + x, y + 46))
                draw.text((x0 + x, y + 306), str(size), fill=fg, font=small)
    # Nearest-neighbor enlargement makes the actual favicon's 16px pixels inspectable.
    draw.text((24, 1390), "Actual 16px favicon / nearest-neighbor 8x inspection", fill=BLUE, font=font)
    for i, theme in enumerate(["light", "dark"]):
        tile = Image.open(previews / f"favicon-16-{theme}.png")
        sheet.paste(tile.resize((128, 128), Image.Resampling.NEAREST), (24 + i * 156, 1420))
    png_save(sheet, ROOT / "contact-sheet.png", provenance)

    checks = {
        "canonical_viewbox": [0, 0, 64, 64], "canonical_ink_bounds": [8, 12, 56, 52],
        "canonical_path_sha256": digest(path.encode()),
        "native_mask_dimensions": [SIZE, SIZE], "native_mask_bytes": len(mask),
        "native_mask_sha256": digest(mask), "native_alpha_range": list(alpha.getextrema()),
        "native_alpha_nonzero_bounds_including_lanczos_fringe": list(alpha.getbbox()),
        "hbmenu_size": list(icon.size), "hbmenu_mode": icon.mode,
        "export_geometry_matches": all(ET.parse(ROOT / name).getroot().find(NS + "path").attrib["d"] == path
                                       for name in ["favicon.svg", "hbmenu-source.svg"]),
    }
    assert checks["export_geometry_matches"] and checks["native_alpha_range"] == [0, 255]
    (ROOT / "checks.json").write_text(json.dumps(checks, indent=2) + "\n")
    rasterizer = subprocess.run(["rsvg-convert", "--version"], capture_output=True, text=True, check=True).stdout.strip()
    files = [p for p in ROOT.rglob("*") if p.is_file()
             and p.name not in {"manifest.json", "finish-review.md", "design-extension.md", "README.md"}
             and "__pycache__" not in p.parts]
    manifest = {
        "authoring": "Moader project logo; original SVG geometry",
        "recipe": RECIPE, "source_sha256": digest(source),
        "tools": {"rasterizer": rasterizer, "pillow": pillow_version},
        "files": {str(p.relative_to(ROOT)): {"sha256": digest(p.read_bytes()), "bytes": p.stat().st_size}
                  for p in sorted(files)},
    }
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(checks, indent=2))


if __name__ == "__main__":
    main()
